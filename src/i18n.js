export function t(locale, key, values = {}) {
  const dictionary = dictionaries[locale] || dictionaries.zh;
  const template = dictionary[key] ?? dictionaries.zh[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

export function dictionaryKeys(locale) {
  return Object.keys(dictionaries[locale] || {});
}

export function fieldName(locale, field) {
  return field?.customName || t(locale, field?.nameKey || 'field.custom');
}

export function playerName(locale, player) {
  return player?.name?.trim() || t(locale, 'player.default', { index: player?.defaultNameIndex || 1 });
}

export function localeTag(locale) {
  return locale === 'en' ? 'en-US' : 'zh-CN';
}

export function formatClock(totalSeconds) {
  const safe = Math.max(0, Math.floor(Number(totalSeconds || 0)));
  const hours = Math.floor(safe / 3600);
  const minutes = Math.floor((safe % 3600) / 60);
  const seconds = safe % 60;
  return hours > 0
    ? `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`
    : `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}

export function formatDateTime(locale, value) {
  if (!value) return '';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  return new Intl.DateTimeFormat(localeTag(locale), { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(date);
}

export function signedNumber(value) {
  const number = Number(value || 0);
  return number > 0 ? `+${number}` : String(number);
}
